create table payments (
    id                  bigint generated by default as identity primary key,
    reference           varchar(20)    not null,
    payment_type        varchar(10)    not null,
    amount              numeric(19, 2) not null,
    currency            varchar(3)     not null,
    debit_account       varchar(34)    not null,
    beneficiary_name    varchar(140)   not null,
    beneficiary_account varchar(34)    not null,
    memo                varchar(140),
    status              varchar(20)    not null,
    required_approvals  integer        not null,
    created_by          varchar(64)    not null,
    idempotency_key     varchar(64),
    created_at          timestamp with time zone not null,
    updated_at          timestamp with time zone not null,
    version             bigint         not null,
    constraint uq_payments_reference unique (reference),
    constraint uq_payments_idempotency unique (created_by, idempotency_key)
);

create index ix_payments_status on payments (status);

create table payment_approvals (
    id          bigint generated by default as identity primary key,
    payment_id  bigint      not null references payments (id),
    approver    varchar(64) not null,
    decision    varchar(10) not null,
    note        varchar(280),
    decided_at  timestamp with time zone not null,
    constraint uq_approval_once_per_user unique (payment_id, approver)
);

create index ix_payment_approvals_payment on payment_approvals (payment_id);
